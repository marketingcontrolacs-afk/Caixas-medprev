create temp table bc_res(revisados int, partes int, regras int, preenchidos int);

do $$ declare cli uuid; conta uuid; r record; m fin_movimentos; n_ok int := 0; n_div int := 0; n_reg int; n_pre int;
begin
  select id into cli from clientes where nome = 'MPA Palmas';
  if cli is null then raise exception 'Empresa MPA Palmas não encontrada'; end if;
  select id into conta from fin_contas where cliente_id = cli and espelho_tes;
  if conta is null then raise exception 'Rode a v57 antes'; end if;
  for r in
    with esp as (
      select x.*, row_number() over (partition by x.data, x.tipo, x.valor order by x.criado_em, x.id) as ord
        from fin_movimentos x where x.conta_id = conta and x.tes_id is not null and x.data between '2023-12-20' and '2025-04-30'
         and not exists (select 1 from fin_movimentos y where y.tes_id = x.tes_id and y.conta_id = conta and y.id <> x.id))
    select e.id, p.* from bc_plan p join esp e on e.data = p.data and e.tipo = case when p.entrada then 'entrada' else 'saida' end
       and e.valor = p.valor and e.ord = p.ord order by e.id, p.parte
  loop
    select * into m from fin_movimentos where id = r.id;
    if r.parte = 0 then
      update fin_movimentos set valor = r.pvalor, categoria = r.categoria, pessoa_nome = r.pessoa,
             documento = coalesce(documento, r.documento), revisado = true, por_regra = false,
             transf_id = case when r.transf then coalesce(transf_id, gen_random_uuid()) else transf_id end
       where id = r.id;
      n_ok := n_ok + 1;
    else
      insert into fin_movimentos (cliente_id, conta_id, data, tipo, valor, descricao, pessoa_nome, documento, categoria,
                                  tes_id, tes_chave, tes_original, revisado, criado_por)
      values (m.cliente_id, m.conta_id, m.data, m.tipo, r.pvalor, m.descricao, r.pessoa, r.documento, r.categoria,
              m.tes_id, m.tes_chave, m.tes_original, true, m.criado_por);
      n_div := n_div + 1;
    end if;
  end loop;
  insert into fin_tes_regras (cliente_id, tipo, chave, categoria, pessoa_nome)
  select cli, b.tipo, b.chave, b.categoria, b.pessoa from bc_regras b on conflict (cliente_id, tipo, chave) do nothing;
  get diagnostics n_reg = row_count;
  update fin_movimentos x set categoria = coalesce(x.categoria, g.categoria), pessoa_nome = coalesce(x.pessoa_nome, g.pessoa_nome)
    from fin_tes_regras g
   where x.conta_id = conta and not x.revisado and x.tes_id is not null and g.cliente_id = cli
     and g.tipo = x.tes_original->>'tipo' and g.chave = x.tes_chave and (x.categoria is null or x.pessoa_nome is null);
  get diagnostics n_pre = row_count;
  raise notice 'Revisados pelo BC: %, partes novas: %, regras: %, preenchidos para revisar: %', n_ok, n_div, n_reg, n_pre;
  insert into bc_res values (n_ok, n_div, n_reg, n_pre);
end $$;

